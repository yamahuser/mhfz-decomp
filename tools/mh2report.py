"""Writes spec\\subsystems\\monster_core.md from analysis\\mh2_matches.csv: per MH2 source file (monsters first) the
matched function count and the key entry points (ChangeState, MotionSounds, State handlers) with MHF addresses.
Facts only (names and addresses), no code."""
import collections, csv, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mh2match as M

mh2 = M.load_mh2()
total = collections.Counter(g["file"] for g in mh2.values())
rows = list(csv.DictReader(open(M.OUT, encoding="utf-8")))
by = collections.defaultdict(list)
for r in rows:
    by[mh2[r["mh2_name"]]["file"]].append(r)
KEY = re.compile(r"(ChangeState|MotionSounds|SetGroup\d*State|_State|_Init|_Update|_Run)")
out = ["# Monster and object core: MH2 to MHF-Z map", "",
       "Generated by `tools/mh2report.py` from `analysis/mh2_matches.csv` (matcher: `tools/mh2match.py`). Facts only:",
       "MH2 (PS2) names and the MHF-Z `mhfo-hd.dll` addresses they map to. Scores and evidence are in the CSV;",
       "call-graph agreement among matched neighbours is about 87%, so treat single low-score rows as hints.", ""]
files = sorted(by, key=lambda f: (not os.path.basename(f).startswith("em_"), -len(by[f])))
for f in files:
    rs = sorted(by[f], key=lambda r: r["mh2_name"])
    out.append(f"## {f.replace(os.sep, '/')}  ({len(rs)} of {total[f]} functions matched)")
    keys = [r for r in rs if KEY.search(r["mh2_name"])]
    show = keys if keys else rs[:8]
    out.append("")
    out.append("| MH2 name | MHF address | score | method |")
    out.append("|---|---|---|---|")
    for r in show[:40]:
        out.append(f"| {r['mh2_name']} | {r['mhf_addr']} | {r['score']} | {r['method'].split(':')[0]} |")
    if len(show) > 40:
        out.append(f"| ... {len(show) - 40} more in the CSV | | | |")
    out.append("")
dst = os.path.join(M.ROOT, "spec", "subsystems", "monster_core.md")
open(dst, "w", encoding="utf-8").write("\n".join(out))
print("wrote", dst, len(files), "files")
